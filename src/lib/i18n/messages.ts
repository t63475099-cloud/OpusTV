export const SUB_SERVER_KEYWORDS: Record<LocaleCode, string[]> = {
  vi: ["vietsub", "việt", "viet", "thuyết minh", "tm", "lồng tiếng"],
  en: ["engsub", "english", "en ", "eng", "multi-sub", "multi sub"],
  zh: ["chinese", "中文", "华语", "国语", "mandarin", "chi"],
  ko: ["korean", "한국어", "kor", "hangul"],
  ja: ["japanese", "日本語", "jap", "jpn"],
  th: ["thai", "ไทย", "th "],
  fr: ["french", "français", "fra", "vf", "vostfr"],
  es: ["spanish", "español", "castellano", "latam", "spa"],
  id: ["indo", "indonesia", "bahasa"],
  pt: ["portugu", "pt-br", "brazilian", "brazil"],
};

export function scoreServerForLocale(serverName: string, locale: LocaleCode): number {
  const n = (serverName || "").toLowerCase();
  let score = 0;
  for (const kw of SUB_SERVER_KEYWORDS[locale] || []) {
    if (n.includes(kw.toLowerCase())) score += 10;
  }
  // mild boost for multi-sub when non-vi
  if (locale !== "vi" && (n.includes("multi") || n.includes("engsub"))) score += 3;
  if (locale === "vi" && (n.includes("vietsub") || n.includes("thuyết"))) score += 5;
  return score;
}

export function pickBestServerIndex(
  servers: { server_name?: string; name?: string }[],
  locale: LocaleCode
): number {
  if (!servers.length) return 0;
  let best = 0;
  let bestScore = -1;
  servers.forEach((s, i) => {
    const name = s.server_name || s.name || "";
    const sc = scoreServerForLocale(name, locale);
    if (sc > bestScore) {
      bestScore = sc;
      best = i;
    }
  });
  return best;
}
